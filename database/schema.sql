-- Ensure you are connected to the 'student_db' database before executing.
-- Example in psql: \c student_db

-- Drop the students table if resetting the schema
-- DROP TABLE IF EXISTS students CASCADE;

-- Create the students table
CREATE TABLE IF NOT EXISTS students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'STUDENT',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT chk_student_role CHECK (role IN ('STUDENT', 'ADMIN'))
);

-- Index on email for rapid lookup during login & duplicate checks
CREATE INDEX IF NOT EXISTS idx_students_email ON students(email);

-- Index on role for filtering and analytics
CREATE INDEX IF NOT EXISTS idx_students_role ON students(role);

